    [Fact]
    public async Task CreatingAUser_CreatesTheirDatabase_AndDeletingTheUser_DeletesIt()
    {
        Guid adminId;
        Guid friendId;
        await using (var scope = _services.CreateAsyncScope())
        {
            await scope.ServiceProvider.GetRequiredService<IDatabaseSeeder>().SeedAsync();
            adminId = (await scope.ServiceProvider.GetRequiredService<PlatformDbContext>().Users.SingleAsync()).Id;

            var users = scope.ServiceProvider.GetRequiredService<IUserService>();
            var friend = await users.CreateUser("friend@example.com", "Friend-Pa55word!", "Friend", false, "en-US", "Europe/Prague", adminId, CancellationToken.None);
            friendId = friend.Id;
        }

        var file = Databases.GetFilePath(friendId);
        Assert.True(File.Exists(file));

        await using (var scope = Scopes.Create(friendId))
        {
            var data = scope.ServiceProvider.GetRequiredService<LogMyDayDbContext>();
            Assert.True(await data.Units.AnyAsync());

            data.Tags.Add(new Tag { TagName = "Coffee", UserId = friendId });
            await data.SaveChangesAsync();
        }

        // The friend's earlier states, from a restore and from an upgrade, and one of the admin's.
        Directory.CreateDirectory(Databases.SnapshotFolder);
        var friendsSnapshots = new[] { $"{friendId:D}-20261101-100000-before-restore.db", $"{friendId:D}-20261102-100000-before-20261120000000_Initial.db" };
        var adminsSnapshot = Path.Combine(Databases.SnapshotFolder, $"{adminId:D}-20261101-100000-before-restore.db");
        foreach (var name in friendsSnapshots)
        {
            File.WriteAllText(Path.Combine(Databases.SnapshotFolder, name), "the friend's data");
        }

        File.WriteAllText(adminsSnapshot, "the admin's data");

        await using (var scope = _services.CreateAsyncScope())
        {
            await scope.ServiceProvider.GetRequiredService<IUserService>().Delete(friendId, adminId, CancellationToken.None);
        }

        Assert.False(File.Exists(file));
        Assert.False(File.Exists(file + "-wal"));
        Assert.False(File.Exists(file + "-shm"));
        Assert.True(File.Exists(Databases.GetFilePath(adminId)));
        Assert.Equal([adminsSnapshot], Directory.GetFiles(Databases.SnapshotFolder));

        await using (var scope = _services.CreateAsyncScope())
        {
            Assert.Null(await scope.ServiceProvider.GetRequiredService<PlatformDbContext>().Users.FindAsync(friendId));
        }
    }

    [Fact]
    public async Task ADeletedUser_GetsNoDatabaseBack_NorDoesAnUnknownOne()
    {
        Guid adminId;
        Guid friendId;
        await using (var scope = _services.CreateAsyncScope())
        {
            await scope.ServiceProvider.GetRequiredService<IDatabaseSeeder>().SeedAsync();
            adminId = (await scope.ServiceProvider.GetRequiredService<PlatformDbContext>().Users.SingleAsync()).Id;

            var users = scope.ServiceProvider.GetRequiredService<IUserService>();
            friendId = (await users.CreateUser("friend@example.com", "Friend-Pa55word!", "Friend", false, "en-US", "UTC", adminId, CancellationToken.None)).Id;
            await users.Delete(friendId, adminId, CancellationToken.None);
        }

        // What a request of the deleted user does, e.g. with a cookie signed before the delete.
        foreach (var userId in new[] { friendId, Guid.NewGuid() })
        {
            await using var scope = Scopes.Create(userId);
            var error = Assert.Throws<InvalidOperationException>(() => scope.ServiceProvider.GetRequiredService<LogMyDayDbContext>());

            Assert.Contains("no account", error.Message);
            Assert.False(File.Exists(Databases.GetFilePath(userId)));
        }

        Assert.Equal([Databases.GetFilePath(adminId)], Directory.GetFiles(Databases.Folder, "*.db"));

        // A connection that a request of the user opened after the delete creates an empty file.
        // It is not taken up as the user's database.
        var leftover = Databases.GetFilePath(friendId);
        await using (var connection = new SqliteConnection($"Data Source={leftover};Pooling=False"))
        {
            await connection.OpenAsync();
        }

        await using (var scope = Scopes.Create(friendId))
        {
            Assert.Throws<InvalidOperationException>(() => scope.ServiceProvider.GetRequiredService<LogMyDayDbContext>());
        }

        Assert.Equal(0, new FileInfo(leftover).Length);
    }

