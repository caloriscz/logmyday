using LogMyDay.Api.Application.Interfaces;
using LogMyDay.Api.Application.Services;
using LogMyDay.Api.Infrastructure.Data;
using LogMyDay.Api.Security;
using LogMyDay.Domain.Entities;
using Microsoft.Data.Sqlite;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Logging.Abstractions;
using Moq;

namespace LogMyDay.Api.Tests;

/// <summary>
/// The configured file is the platform database, and each user's data is a file of its own next
/// to it. A scope works on one user's file, and nothing reaches another user's rows through it.
/// </summary>
public sealed class UserDatabaseTests : IDisposable
{
    private static readonly Guid Alice = Guid.Parse("aaaaaaaa-0000-0000-0000-000000000001");
    private static readonly Guid Bob = Guid.Parse("bbbbbbbb-0000-0000-0000-000000000002");

    private readonly string _folder = Path.Combine(Path.GetTempPath(), $"lmd-user-db-test-{Guid.NewGuid():N}");
    private readonly ServiceProvider _services;

    public UserDatabaseTests()
    {
        Directory.CreateDirectory(_folder);

        var hasher = new Mock<IPasswordHasher>();
        hasher.Setup(h => h.Hash(It.IsAny<string>())).Returns("hash");

        var services = new ServiceCollection();
        services.AddLogging();
        services.AddLogMyDayDatabases($"Data Source={PlatformPath}");
        services.AddSingleton(hasher.Object);
        services.AddScoped<IUserDirectory, UserDirectory>();
        services.AddScoped<IReminderDayBackfill, ReminderDayBackfill>();
        services.AddScoped<IReminderRecurrenceMigration, ReminderRecurrenceMigration>();
        services.AddScoped<IDatabaseSeeder, DatabaseSeeder>();
        services.AddSingleton(new Mock<IEmailSender>().Object);
        services.AddScoped<IUserService, UserService>();
        _services = services.BuildServiceProvider();
    }

    private string PlatformPath => Path.Combine(_folder, "logmyday.db");

    private UserDatabases Databases => _services.GetRequiredService<UserDatabases>();

    private IUserScopeFactory Scopes => _services.GetRequiredService<IUserScopeFactory>();

    public void Dispose()
    {
        _services.Dispose();
        SqliteConnection.ClearAllPools();
        Directory.Delete(_folder, recursive: true);
    }

    [Fact]
    public void AUsersDatabase_IsAFileNamedAfterTheUser_NextToThePlatformDatabase()
    {
        Assert.Equal(Path.Combine(_folder, "users", "aaaaaaaa-0000-0000-0000-000000000001.db"), Databases.GetFilePath(Alice));
        Assert.Equal(Databases.GetFilePath(Alice), DatabaseLocation.GetFilePath(Databases.GetConnectionString(Alice)));
    }

    [Fact]
    public void ADatabaseThatIsNotAFile_IsRefused()
    {
        Assert.Throws<NotSupportedException>(() => new UserDatabases("Data Source=:memory:", NullLogger<UserDatabases>.Instance));
    }

    [Fact]
    public async Task Startup_OnAnEmptyFolder_CreatesThePlatformAndTheAdminsDatabase()
    {
        await using (var scope = _services.CreateAsyncScope())
        {
            await scope.ServiceProvider.GetRequiredService<IDatabaseSeeder>().SeedAsync();
        }

        Guid adminId;
        await using (var scope = _services.CreateAsyncScope())
        {
            var platform = scope.ServiceProvider.GetRequiredService<PlatformDbContext>();
            adminId = (await platform.Users.SingleAsync(u => u.IsAdmin)).Id;

            // The platform database holds the platform tables only.
            Assert.Equal(0, await TableCount(PlatformPath, "LogMyDay_Activities"));
            Assert.Equal(1, await TableCount(PlatformPath, "LogMyDay_Users"));
        }

        Assert.True(File.Exists(Databases.GetFilePath(adminId)));
        Assert.Equal(0, await TableCount(Databases.GetFilePath(adminId), "LogMyDay_Users"));

        await using var adminScope = Scopes.Create(adminId);
        var data = adminScope.ServiceProvider.GetRequiredService<LogMyDayDbContext>();
        Assert.Empty(await data.Database.GetPendingMigrationsAsync());
        Assert.True(await data.Units.AnyAsync());
        Assert.True(await data.InputTypes.AnyAsync());

        // Keys are generated by the database, as on a migrated one.
        var tag = new Tag { TagName = "Water", UserId = adminId };
        data.Tags.Add(tag);
        await data.SaveChangesAsync();
        Assert.True(tag.Id > 0);
    }

    [Fact]
    public async Task EachUser_ReadsAndWritesOnlyTheirOwnDatabase()
    {
        await using (var scope = Scopes.Create(Alice))
        {
            var data = scope.ServiceProvider.GetRequiredService<LogMyDayDbContext>();
            data.Tags.Add(new Tag { TagName = "Alice's tag", UserId = Alice });
            await data.SaveChangesAsync();
        }

        await using (var scope = Scopes.Create(Bob))
        {
            var data = scope.ServiceProvider.GetRequiredService<LogMyDayDbContext>();
            Assert.Empty(await data.Tags.Where(t => t.UserId != null).ToListAsync());

            data.Tags.Add(new Tag { TagName = "Bob's tag", UserId = Bob });
            await data.SaveChangesAsync();
        }

        await using (var scope = Scopes.Create(Alice))
        {
            var data = scope.ServiceProvider.GetRequiredService<LogMyDayDbContext>();
            Assert.Equal(["Alice's tag"], await data.Tags.Where(t => t.UserId != null).Select(t => t.TagName).ToListAsync());
        }

        Assert.True(File.Exists(Databases.GetFilePath(Alice)));
        Assert.True(File.Exists(Databases.GetFilePath(Bob)));
        Assert.NotEqual(Databases.GetFilePath(Alice), Databases.GetFilePath(Bob));
    }

    [Fact]
    public async Task ARowOfAnotherUser_CantBeSavedIntoAUsersDatabase()
    {
        await using var scope = Scopes.Create(Alice);
        var data = scope.ServiceProvider.GetRequiredService<LogMyDayDbContext>();
        data.Tags.Add(new Tag { TagName = "Smuggled", UserId = Bob });

        var error = await Assert.ThrowsAsync<InvalidOperationException>(() => data.SaveChangesAsync());

        Assert.Contains(Bob.ToString(), error.Message);
        Assert.Contains(Alice.ToString(), error.Message);
    }

    [Fact]
    public async Task AScopeForNoUser_CantReachAnyData()
    {
        await using var scope = _services.CreateAsyncScope();
        var data = scope.ServiceProvider.GetRequiredService<LogMyDayDbContext>();

        var error = await Assert.ThrowsAsync<InvalidOperationException>(() => data.Tags.ToListAsync());

        Assert.Equal(NoUserInterceptor.Message, error.Message);
        Assert.False(Directory.Exists(Databases.Folder));
    }

    [Fact]
    public async Task AScope_CantChangeItsUser_OnceTheDataWasReached()
    {
        await using var scope = Scopes.Create(Alice);
        scope.ServiceProvider.GetRequiredService<LogMyDayDbContext>();
        var userScope = scope.ServiceProvider.GetRequiredService<UserDatabaseScope>();

        userScope.Use(Alice);
        Assert.Throws<InvalidOperationException>(() => userScope.Use(Bob));
    }

    [Fact]
    public async Task CreatingAUser_CreatesTheirDatabase_AndDeletingTheUser_DeletesIt()
    {
        Guid adminId;
        Guid friendId;
        await using (var scope = _services.CreateAsyncScope())
        {
            await scope.ServiceProvider.GetRequiredService<IDatabaseSeeder>().SeedAsync();
            adminId = (await scope.ServiceProvider.GetRequiredService<PlatformDbContext>().Users.SingleAsync()).Id;

            var users = scope.ServiceProvider.GetRequiredService<IUserService>();
            var friend = await users.CreateUser("friend@example.com", "Friend-Pa55word!", "Friend", false, "en-US", "Europe/Prague", adminId, CancellationToken.None);
            friendId = friend.Id;
        }

        var file = Databases.GetFilePath(friendId);
        Assert.True(File.Exists(file));

        await using (var scope = Scopes.Create(friendId))
        {
            var data = scope.ServiceProvider.GetRequiredService<LogMyDayDbContext>();
            Assert.True(await data.Units.AnyAsync());

            data.Tags.Add(new Tag { TagName = "Coffee", UserId = friendId });
            await data.SaveChangesAsync();
        }

        await using (var scope = _services.CreateAsyncScope())
        {
            await scope.ServiceProvider.GetRequiredService<IUserService>().Delete(friendId, adminId, CancellationToken.None);
        }

        Assert.False(File.Exists(file));
        Assert.False(File.Exists(file + "-wal"));
        Assert.False(File.Exists(file + "-shm"));
        Assert.True(File.Exists(Databases.GetFilePath(adminId)));

        await using (var scope = _services.CreateAsyncScope())
        {
            Assert.Null(await scope.ServiceProvider.GetRequiredService<PlatformDbContext>().Users.FindAsync(friendId));
        }
    }

    [Fact]
    public async Task Startup_Stops_WhenAUsersDatabaseCantBeMigrated_AndNamesTheFile()
    {
        await using (var scope = _services.CreateAsyncScope())
        {
            await scope.ServiceProvider.GetRequiredService<IDatabaseSeeder>().SeedAsync();

            var platform = scope.ServiceProvider.GetRequiredService<PlatformDbContext>();
            platform.Users.Add(new User { Id = Bob, Email = "bob@example.com", DisplayName = "Bob", PasswordHash = "hash", Culture = "en-US", TimeZone = "UTC" });
            await platform.SaveChangesAsync();
        }

        // Bob's file comes from somewhere else: it has a table, and no migration of this version.
        var file = Databases.GetFilePath(Bob);
        await using (var connection = new SqliteConnection($"Data Source={file};Pooling=False"))
        {
            await connection.OpenAsync();
            await using var command = connection.CreateCommand();
            command.CommandText = "CREATE TABLE LogMyDay_Tags (Id INTEGER PRIMARY KEY);";
            await command.ExecuteNonQueryAsync();
        }

        await using var startup = _services.CreateAsyncScope();
        var error = await Assert.ThrowsAsync<InvalidOperationException>(
            () => startup.ServiceProvider.GetRequiredService<IDatabaseSeeder>().SeedAsync());

        Assert.Contains(file, error.Message);
    }

    private static async Task<long> TableCount(string path, string table)
    {
        await using var connection = new SqliteConnection($"Data Source={path};Mode=ReadOnly;Pooling=False");
        await connection.OpenAsync();
        await using var command = connection.CreateCommand();
        command.CommandText = "SELECT COUNT(*) FROM sqlite_master WHERE type = 'table' AND name = $name;";
        command.Parameters.AddWithValue("$name", table);

        return (long)(await command.ExecuteScalarAsync())!;
    }
}
